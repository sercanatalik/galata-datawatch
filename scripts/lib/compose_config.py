"""Compose the deployment's configuration document (compose-deployment-config).

    python3 scripts/lib/compose_config.py <root>              compose, print the path to read
    python3 scripts/lib/compose_config.py <root> --check [FILE]
                                                         the same refusals; writes nothing of
                                                         the deployment's. Given FILE (outside
                                                         var/), the composition goes there and
                                                         its path is printed, so a check reads
                                                         what a start would
    python3 scripts/lib/compose_config.py <root> --migrate    once: a hand-kept document to an overlay

**The document a deployed service reads** is the committed
`config/datawatch.toml` followed by this machine's overlay,
`var/datawatch.overlay.toml`, appended as text under a generated header and
written to `var/datawatch.local.toml`. Appended, never merged: the committed
comments survive, and the overlay can add a machine's own tables (`[broker]`,
`[ledger]`) but never change a committed one. A table in both is refused by
name.

**The header carries the body's digest**, so a document edited by hand after
it was composed is found and refused, never overwritten: the edit belongs in
the committed file or the overlay. A document with no header is hand-kept,
from before this; `--migrate` turns it into an overlay, and only when the
composition parses to exactly what it did.

No overlay and no local document: services read the committed file, as
before. Prints the path to read on stdout; a refusal goes to stderr and exits
1. Names only ever pass through here; the values are in the vault.
"""

import hashlib
import os
import pathlib
import re
import sys
import tomllib

COMMITTED = "config/datawatch.toml"
OVERLAY = "var/datawatch.overlay.toml"
LOCAL = "var/datawatch.local.toml"
HAND_KEPT = "var/datawatch.local.toml.hand-kept"

FIRST_LINE = "# GENERATED by scripts/compose-config.sh — do not edit."
SECOND_LINE = "# Edit config/datawatch.toml (committed) or var/datawatch.overlay.toml (this machine)."
DIGEST = re.compile(r"^# body-sha256: ([0-9a-f]{64})$")
SEAM = "\n# ---- this machine: var/datawatch.overlay.toml ----\n\n"
HEADER_LINE = re.compile(r"^\[\[?\s*([A-Za-z0-9_-]+|\"[^\"]*\")")


class Refused(Exception):
    pass


def parse(text, what):
    try:
        return tomllib.loads(text)
    except tomllib.TOMLDecodeError as e:
        raise Refused(f"{what} does not parse: {e}")


def shared_tables(a, b, prefix=""):
    """The deepest table paths both documents declare."""
    found = []
    for key in sorted(set(a) & set(b)):
        path = f"{prefix}{key}"
        if isinstance(a[key], dict) and isinstance(b[key], dict):
            deeper = shared_tables(a[key], b[key], path + ".")
            found.extend(deeper or [path])
        else:
            # A key, or an array of tables, in both: refused by its own name.
            found.append(path)
    return found


def first_difference(a, b, prefix=""):
    for key in sorted(set(a) | set(b)):
        path = f"{prefix}{key}"
        if key not in a or key not in b:
            return path
        if isinstance(a[key], dict) and isinstance(b[key], dict):
            inner = first_difference(a[key], b[key], path + ".")
            if inner:
                return inner
        elif a[key] != b[key]:
            return path
    return None


def compose(committed_text, overlay_text):
    """The document's full text, or a refusal."""
    committed = parse(committed_text, COMMITTED)
    overlay = parse(overlay_text, OVERLAY)
    bare = [k for k, v in overlay.items() if not isinstance(v, (dict, list))]
    if bare:
        raise Refused(
            f"{OVERLAY} declares {', '.join(bare)} outside any table; appended, it would "
            f"land in the committed file's last table"
        )
    both = shared_tables(committed, overlay)
    if both:
        raise Refused(
            f"{OVERLAY} declares {', '.join(both)}, which {COMMITTED} also declares: the "
            f"overlay adds this machine's tables and never changes a committed one"
        )
    body = committed_text.rstrip("\n") + "\n" + SEAM + overlay_text.rstrip("\n") + "\n"
    composed = parse(body, "the composed document")
    want = dict(committed)
    want.update(overlay)
    where = first_difference(want, composed)
    if where:
        raise Refused(f"the composed document reads {where} differently from its two sources")
    digest = hashlib.sha256(body.encode()).hexdigest()
    return f"{FIRST_LINE}\n{SECOND_LINE}\n# body-sha256: {digest}\n\n{body}"


def state_of(text):
    """'generated', 'edited' or 'hand-kept'."""
    lines = text.split("\n", 4)
    if len(lines) < 4 or lines[0] != FIRST_LINE:
        return "hand-kept"
    m = DIGEST.match(lines[2])
    body = lines[4] if len(lines) > 4 else ""
    if not m or hashlib.sha256(body.encode()).hexdigest() != m.group(1):
        return "edited"
    return "generated"


def write_atomically(path, text):
    tmp = path.with_name(f".{path.name}.{os.getpid()}")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        parse(tmp.read_text(), f"the document written to {tmp}")
        os.replace(tmp, path)
    finally:
        if tmp.exists():
            tmp.unlink()


def run(root, check, into=None):
    committed, overlay, local = root / COMMITTED, root / OVERLAY, root / LOCAL
    if not committed.is_file():
        raise Refused(f"no {COMMITTED}")
    if local.exists():
        state = state_of(local.read_text())
        if state == "edited":
            raise Refused(
                f"{LOCAL} was edited by hand after it was composed; nothing is overwritten. "
                f"Move the edit to {COMMITTED} (committed) or {OVERLAY} (this machine), "
                f"then delete {LOCAL}"
            )
        if state == "hand-kept":
            if overlay.exists():
                raise Refused(
                    f"{LOCAL} is hand-kept and {OVERLAY} exists too: one of them is stale. "
                    f"Move what the hand-kept document holds into the overlay and delete it"
                )
            raise Refused(f"{LOCAL} is hand-kept; run scripts/compose-config.sh --migrate once")
    if not overlay.exists():
        if local.exists():
            raise Refused(
                f"{LOCAL} was composed from an overlay, and {OVERLAY} is gone: restore the "
                f"overlay, or delete {LOCAL} to read {COMMITTED} alone"
            )
        return committed
    text = compose(committed.read_text(), overlay.read_text())
    if check:
        if into is None:
            return local
        into.write_text(text)
        return into
    write_atomically(local, text)
    return local


def migrate(root):
    committed_path, overlay, local, kept = root / COMMITTED, root / OVERLAY, root / LOCAL, root / HAND_KEPT
    if overlay.exists():
        raise Refused(f"{OVERLAY} already exists: there is nothing to migrate")
    if not local.exists():
        raise Refused(f"no {LOCAL} to migrate")
    local_text = local.read_text()
    if state_of(local_text) != "hand-kept":
        raise Refused(f"{LOCAL} is already composed")
    if kept.exists():
        raise Refused(f"{HAND_KEPT} already exists; move it aside first")
    committed_text = committed_path.read_text()
    committed = parse(committed_text, COMMITTED)
    hand = parse(local_text, LOCAL)
    own = [k for k in hand if k not in committed]

    # Each of the machine's tables, as its text: from the comment block just
    # above its header (up to a blank line) to the next header of another
    # table. Headers are recognised at the start of a line only.
    lines = local_text.split("\n")
    owner = [None] * len(lines)
    current = None
    for i, line in enumerate(lines):
        m = HEADER_LINE.match(line)
        if m:
            current = m.group(1).strip('"')
        owner[i] = current
    for i in range(len(lines) - 1, -1, -1):
        if HEADER_LINE.match(lines[i]):
            j = i - 1
            while j >= 0 and lines[j].startswith("#"):
                owner[j] = owner[i]
                j -= 1
    picked = [line for line, key in zip(lines, owner) if key in own]
    overlay_text = "\n".join(picked).strip("\n") + "\n"
    if not own:
        raise Refused(f"{LOCAL} holds no table {COMMITTED} lacks: delete it and read the committed file")

    text = compose(committed_text, overlay_text)
    composed = parse(text, "the composed document")
    where = first_difference(hand, composed)
    if where:
        raise Refused(
            f"the composition would read {where} differently from {LOCAL}: the hand-kept "
            f"document has drifted from {COMMITTED}. Nothing is changed"
        )
    os.rename(local, kept)
    write_atomically(overlay, overlay_text)
    write_atomically(local, text)
    return own


def main(argv):
    ok = (len(argv) == 2
          or (len(argv) == 3 and argv[2] in ("--check", "--migrate"))
          or (len(argv) == 4 and argv[2] == "--check"))
    if not ok:
        print("usage: compose_config.py <root> [--check [FILE] | --migrate]", file=sys.stderr)
        return 2
    root = pathlib.Path(argv[1]).resolve()
    try:
        if len(argv) == 3 and argv[2] == "--migrate":
            own = migrate(root)
            print(f"migrated: {OVERLAY} holds {', '.join('[' + k + ']' for k in own)}; "
                  f"the hand-kept document is {HAND_KEPT}")
        else:
            into = pathlib.Path(argv[3]) if len(argv) == 4 else None
            print(run(root, check=len(argv) >= 3, into=into))
    except Refused as e:
        print(f"compose-config: REFUSED — {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
